// Helper function to get translation
export const getUserManagementTranslation = (
  key: keyof typeof userManagementTranslations.en,
  language: "en" | "az" | "ru"
): string => {
  return userManagementTranslations[language][key] || userManagementTranslations.en[key] || key;
};

// Helper to translate module names
export const translateModuleName = (moduleName: string, language: "en" | "az" | "ru"): string => {
  const moduleMap: Record<string, keyof typeof userManagementTranslations.en> = {
    "Dashboard": "dashboard",
    "Inventory": "inventory",
    "Stock": "stock",
    "Sales": "sales",
    "Purchases": "purchases",
    "Finances": "finances",
    "People": "people",
    "Users": "people",
    "Reservations": "reservations",
    "Reports": "reports",
    "User Management": "usermanagement",
    "Settings": "settings",
  };

  const key = moduleMap[moduleName];
  if (key) {
    return getUserManagementTranslation(key, language);
  }
  return moduleName;
};